import { chromium } from "@playwright/test";
const browser = await chromium.launch({
  executablePath: "/opt/google/chrome/chrome",
  args: ["--disable-background-networking", "--no-first-run"],
});
const ctx = await browser.newContext();
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
const out = {};
await page.goto("http://localhost:3000/account");
await page.waitForURL(/sign-in/);
out.redirected = page.url();
const email = `qa-${Date.now()}@example.test`;
// Add to cart as guest first, to verify merge on sign-up.
await page.goto("http://localhost:3000/products/trace-tag", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Add to cart/ }).click();
await page.getByText(/Added to cart/).waitFor();
await page.goto("http://localhost:3000/sign-up?next=/account/addresses");
await page.getByLabel("Name").fill("QA Tester");
await page.getByLabel("Email").fill(email);
await page.getByLabel(/^Password/).fill("short");
await page.getByLabel("Confirm password").fill("short");
await page.getByRole("button", { name: "Create account" }).click();
await page.getByText("Use at least 10 characters.").waitFor();
await page.getByLabel(/^Password/).fill("correct-horse-battery");
await page.getByLabel("Confirm password").fill("correct-horse-battery");
await page.getByRole("button", { name: "Create account" }).click();
await page.waitForURL("http://localhost:3000/account/addresses");
out.afterSignup = page.url();
out.cart = await page.getByRole("link", { name: /^Cart,/ }).getAttribute("aria-label");
await page.getByLabel("Full name").fill("QA Tester");
await page.getByLabel("Address", { exact: true }).fill("1 rue Test");
await page.getByLabel("Postal code").fill("34000");
await page.getByLabel("City").fill("Montpellier");
await page.getByRole("button", { name: "Save address" }).click();
await page.getByText("Address saved.").waitFor();
out.addresses = await page.locator("address").count();
await page.goto("http://localhost:3000/account");
await page.getByRole("button", { name: "Sign out" }).click();
await page.waitForURL("http://localhost:3000/");
await page.goto("http://localhost:3000/sign-in");
await page.getByLabel("Email").fill(email);
await page.getByLabel("Password").fill("wrong-password-123");
await page.getByRole("button", { name: "Sign in" }).click();
await page.getByText("Email or password is incorrect.").waitFor();
out.wrong = "generic message shown";
await page.goto("http://localhost:3000/sign-in?next=https://evil.example");
await page.getByLabel("Email").fill(email);
await page.getByLabel("Password").fill("correct-horse-battery");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL("http://localhost:3000/account");
out.openRedirectBlocked = page.url();
out.errors = errors;
console.log(JSON.stringify(out, null, 1));
await browser.close();
