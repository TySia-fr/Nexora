import type { CSSProperties } from "react";

/**
 * Conceptual diagram of active noise cancelling: an ambient waveform, the inverted
 * signal the headphones generate, and the small residual you hear. The curves are
 * illustrative, computed from sines, and labelled as such: they are not measurements.
 * Each curve wipes in from the left when its row scrolls into view (RevealObserver
 * animates the clip of .anc-draw).
 */

const W = 560;
const H = 64;
const STEPS = 140;

function wave(fn: (t: number) => number): string {
  let d = "";
  for (let i = 0; i <= STEPS; i++) {
    const t = i / STEPS;
    const x = (t * W).toFixed(1);
    const y = (H / 2 - fn(t) * (H / 2 - 4)).toFixed(1);
    d += `${i ? "L" : "M"}${x} ${y}`;
  }
  return d;
}

const noise = (t: number) =>
  0.55 * Math.sin(t * Math.PI * 9) +
  0.3 * Math.sin(t * Math.PI * 23 + 1.2) +
  0.15 * Math.sin(t * Math.PI * 41 + 0.4);

const rows = [
  {
    label: "Ambient noise",
    note: "Picked up by the outer microphones",
    d: wave(noise),
    tone: "stroke-fg-muted",
  },
  {
    label: "Inverted signal",
    note: "Generated by the driver, in opposite phase",
    d: wave((t) => -noise(t)),
    tone: "stroke-signal",
  },
  {
    label: "What reaches you",
    note: "The residual after the two cancel",
    d: wave((t) => 0.08 * noise(t)),
    tone: "stroke-fg",
  },
];

export function AncDiagram() {
  return (
    <figure className="flex flex-col gap-2" aria-labelledby="anc-caption">
      {rows.map((r, i) => (
        <div
          key={r.label}
          className="grid grid-cols-[32px_1fr] items-center gap-x-4 border-t border-line py-4"
          data-reveal
          style={{ "--reveal-delay": `${120 + i * 140}ms` } as CSSProperties}
        >
          <span className="label-mono self-start pt-0.5 text-fg-subtle">
            {String(i + 1).padStart(2, "0")}
          </span>
          <div className="flex flex-col gap-3">
            <div className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
              <span className="text-[15px] font-medium">{r.label}</span>
              <span className="text-[12px] text-fg-subtle">{r.note}</span>
            </div>
            <svg
              viewBox={`0 0 ${W} ${H}`}
              className="anc-draw h-12 w-full overflow-visible md:h-16"
              preserveAspectRatio="none"
              aria-hidden="true"
            >
              <line
                x1="0"
                x2={W}
                y1={H / 2}
                y2={H / 2}
                className="stroke-line-strong"
                strokeDasharray="2 6"
                vectorEffect="non-scaling-stroke"
              />
              <path
                d={r.d}
                fill="none"
                strokeWidth={1.6}
                className={r.tone}
                vectorEffect="non-scaling-stroke"
              />
            </svg>
          </div>
        </div>
      ))}
      <figcaption id="anc-caption" className="label-mono border-t border-line pt-4 text-fg-subtle">
        Fig. 03 — Active noise cancelling, conceptual. Illustrative curves, not measured data.
      </figcaption>
    </figure>
  );
}
